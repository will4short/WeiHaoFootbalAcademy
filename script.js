  const coveredSections = new Set();
  const contactObserver = new IntersectionObserver(entries => {
    entries.forEach(entry => entry.isIntersecting ? coveredSections.add(entry.target) : coveredSections.delete(entry.target));
    floatingWhatsApp.classList.toggle('is-hidden', coveredSections.size > 0);
  }, { rootMargin: '0px 0px -15% 0px' });
  contactObserver.observe(document.getElementById('contact'));
